"""Migration tests: models match the migrations, and a legacy database upgrades."""

from decimal import Decimal

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.engine import make_url

from app.migrate import _alembic_config, run_migrations


def test_models_match_migrations(client, pg_url):
    """`alembic check`: fails if a model changed without a migration."""
    engine = create_engine(pg_url)
    with engine.connect() as conn:
        try:
            command.check(_alembic_config(conn))
        except AutogenerateDiffsDetected as exc:  # pragma: no cover
            pytest.fail(f"Models and migrations differ, add a migration: {exc}")
    engine.dispose()


def test_legacy_database_is_stamped_and_upgraded(pg_url):
    """A database made by the old create_all (float money, no alembic_version,
    missing ad-hoc columns) is upgraded without losing data."""
    admin = create_engine(pg_url, isolation_level="AUTOCOMMIT")
    with admin.connect() as conn:
        conn.execute(text("DROP DATABASE IF EXISTS legacy_test"))
        conn.execute(text("CREATE DATABASE legacy_test"))
    admin.dispose()

    legacy_url = make_url(pg_url).set(database="legacy_test")
    engine = create_engine(legacy_url)
    with engine.begin() as conn:
        conn.execute(text("""
            CREATE TABLE transactions (
                id VARCHAR(36) PRIMARY KEY, date VARCHAR(10) NOT NULL, type VARCHAR(16) NOT NULL,
                amount DOUBLE PRECISION NOT NULL, currency VARCHAR(8) NOT NULL, category VARCHAR(64) NOT NULL,
                notes VARCHAR NOT NULL, recurring BOOLEAN NOT NULL, created_at BIGINT NOT NULL,
                kind VARCHAR(32) NOT NULL, payment_method VARCHAR(16) NOT NULL)
        """))
        conn.execute(text("""
            CREATE TABLE debts (
                id VARCHAR(36) PRIMARY KEY, type VARCHAR(16) NOT NULL, label VARCHAR(255) NOT NULL,
                amount DOUBLE PRECISION NOT NULL, currency VARCHAR(8) NOT NULL, date VARCHAR(10) NOT NULL,
                deadline VARCHAR(10) NOT NULL, notes VARCHAR NOT NULL, status VARCHAR(16) NOT NULL,
                created_at BIGINT NOT NULL)
        """))
        conn.execute(text("""
            CREATE TABLE monthly_funds (
                year_month VARCHAR(7) PRIMARY KEY, commitments DOUBLE PRECISION NOT NULL,
                personal DOUBLE PRECISION NOT NULL, investment DOUBLE PRECISION NOT NULL)
        """))
        conn.execute(text("""
            CREATE TABLE settings (
                id INTEGER PRIMARY KEY, language VARCHAR(8) NOT NULL, theme VARCHAR(16) NOT NULL,
                salary DOUBLE PRECISION NOT NULL, fund_splits_commitments DOUBLE PRECISION NOT NULL,
                fund_splits_personal DOUBLE PRECISION NOT NULL, fund_splits_investment DOUBLE PRECISION NOT NULL)
        """))
        conn.execute(text(
            "INSERT INTO transactions VALUES "
            "('t1', '2026-01-05', 'expense', 12.345, 'TND', 'food', '', false, 0, 'normal', 'cash')"
        ))
        conn.execute(text("INSERT INTO settings VALUES (1, 'ar', 'light', 1000.5, 40, 20, 40)"))

    run_migrations(engine)
    run_migrations(engine)  # second run must be a no-op

    with engine.connect() as conn:
        cols = {c["name"]: c for c in inspect(conn).get_columns("transactions")}
        assert str(cols["amount"]["type"]) == "NUMERIC(12, 3)"
        assert "card_settled" in cols
        assert conn.execute(text("SELECT amount FROM transactions")).scalar_one() == Decimal("12.345")
        assert conn.execute(text("SELECT cash_balance_offset FROM settings")).scalar_one() == 0
        assert conn.execute(text("SELECT version_num FROM alembic_version")).scalar_one()
    engine.dispose()
